import { articles } from './articles';
import type { SeedContent } from './content';
import { experience } from './experience';
import { profile } from './profile';
import { projects } from './projects';
import { quotes } from './quotes';
import { settings } from './settings';
import { skillGroups } from './skills';
import { socialLinks } from './social-links';
import {
  stressArticles,
  stressExperience,
  stressProjects,
  stressQuotes,
  stressSkillGroup,
  stressSocialLinks,
} from './stress';

export type { SeedContent };

/** Renumbers a list's order after the stress cases are appended. */
const ordered = <T extends object>(items: T[]) =>
  items.map((item, i) => ({ ...item, sortOrder: i + 1 }));

/**
 * The one dataset: the shipped placeholders (the mockup's copy) plus the stress cases. It is
 * `supabase/seed.sql` (generated by `lib/repositories/supabase/seed.ts`), what CI's local
 * Supabase starts from, and the data unit tests of pure logic read. Real content is entered
 * through the admin, never here.
 */
export const seedContent: SeedContent = {
  profile,
  experience: ordered([...experience, ...stressExperience]),
  projects: ordered([...projects, ...stressProjects]),
  articles: [...articles, ...stressArticles],
  skillGroups: ordered([...skillGroups.slice(0, 3), stressSkillGroup]),
  quotes: ordered([...quotes, ...stressQuotes]),
  socialLinks: ordered([...socialLinks, ...stressSocialLinks]),
  settings,
};
